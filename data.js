          <p>תנאי שפה מגדירים את התנהגות הפונקציה או נגזרותיה בקצוות התחום המרחבי שבו נפתרת המשוואה (למשל, בקצוות מוט באורך $L$, כלומר ב-$x=0$ וב-$x=L$). מספר תנאי השפה הנדרשים נקבע לפי סדר הנגזרת המרחבית הגבוה ביותר (למשל, עבור נגזרת שנייה $u_{xx}$ נדרשים שני תנאי שפה, אחד לכל קצה).</p>
          
